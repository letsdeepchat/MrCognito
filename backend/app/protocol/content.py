# Phase 4 endgames: (fen, side to move is the trainee, short description). Trainee side is better.
PERTURBATION_ENDGAMES: list[tuple[str, str]] = [
    ("8/5pk1/6p1/8/8/6P1/4RPKP/1r6 w - - 0 1", "rook endgame, equal pawns, activity matters"),
    ("8/8/4k3/8/2KP4/8/8/8 w - - 0 1", "king and pawn vs king"),
    ("6k1/5ppp/8/8/8/8/3R1PPP/6K1 w - - 0 1", "rook vs pawns, back-rank awareness"),
    ("4k3/8/8/8/8/8/3PPP2/4K2R w K - 0 1", "rook and pawns vs bare king"),
    ("8/8/3k4/8/3K4/3B4/3N4/8 w - - 0 1", "bishop and knight coordination"),
    ("2r3k1/5ppp/8/8/8/8/1Q3PPP/6K1 w - - 0 1", "queen vs rook"),
    ("8/5k2/8/8/8/2N5/5PPP/2B3K1 w - - 0 1", "minor pieces and pawns vs king"),
    ("6k1/8/6K1/6P1/8/8/8/R7 w - - 0 1", "rook + pawn, cutting the king"),
]


@lru_cache
def puzzles() -> list[dict]:
    p = CONTENT_DIR / "puzzles.json"
    return json.loads(p.read_text()) if p.exists() else []


@lru_cache
def sparring_positions() -> list[dict]:
    p = CONTENT_DIR / "sparring.json"
    return json.loads(p.read_text()) if p.exists() else []


def pick_puzzles(rating: float, n: int, rng: random.Random, exclude: set[str] = frozenset()) -> list[dict]:
    bank = [p for p in puzzles() if p["id"] not in exclude] or puzzles()
    bank = sorted(bank, key=lambda p: abs(p["rating"] - rating))
    window = bank[: max(n * 3, 6)]
    rng.shuffle(window)
    return window[:n]


def pick_sparring(rating: float, rng: random.Random) -> dict:
    bank = sparring_positions()
    if not bank:
        return {"id": "fallback", "fen": "r1bq1rk1/pp2bppp/2n1pn2/3p4/2PP4/2N2N2/PP2BPPP/R2QKB1R w KQ - 0 9",
                "theme": "isolated-queen-pawn middlegame"}
    return rng.choice(bank)


def fragment(rng: random.Random, n_moves: int) -> dict:
    name, line = rng.choice(list(OPENING_LINES.items()))
    max_start = len(line) - n_moves
    start = rng.randint(max(2, max_start - 6), max_start)
    board = chess.Board()
    for san in line[:start]:
        board.push_san(san)
    return {"opening": name, "start_fen": board.fen(), "moves": line[start:start + n_moves]}


def validate_content() -> list[str]:
    """Used by tests: every FEN/SAN in the bank must be legal."""
    errors = []
    for name, line in OPENING_LINES.items():
        b = chess.Board()
        try:
            for san in line:
                b.push_san(san)
        except ValueError as exc:
            errors.append(f"{name}: {exc}")
    for fen, desc in PERTURBATION_ENDGAMES:
        if not chess.Board(fen).is_valid():
            errors.append(f"endgame {desc}: invalid")
    for p in puzzles() + sparring_positions():
        b = chess.Board(p["fen"])
        if not b.is_valid():
            errors.append(f"{p['id']}: invalid fen")
        for key in ("tempting_uci", "solution_uci"):
            if key in p and chess.Move.from_uci(p[key]) not in b.legal_moves:
                errors.append(f"{p['id']}: {key} illegal")
    return errors
